-- Run once in the Supabase SQL Editor for the wedding guestbook.
create table if not exists public.guestbook_messages (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(btrim(name)) between 1 and 60),
  message text not null check (char_length(btrim(message)) between 1 and 500),
  created_at timestamptz not null default now()
);

create index if not exists guestbook_messages_created_at_idx
  on public.guestbook_messages (created_at desc);

alter table public.guestbook_messages enable row level security;

revoke all on table public.guestbook_messages from anon, authenticated;
grant select on table public.guestbook_messages to anon;
grant insert (name, message) on table public.guestbook_messages to anon;
revoke all on sequence public.guestbook_messages_id_seq from anon, authenticated;
grant usage, select on sequence public.guestbook_messages_id_seq to anon;

drop policy if exists "Anyone can read guestbook messages" on public.guestbook_messages;
create policy "Anyone can read guestbook messages"
  on public.guestbook_messages
  for select
  to anon
  using (true);

drop policy if exists "Visitors can post guestbook messages" on public.guestbook_messages;
create policy "Visitors can post guestbook messages"
  on public.guestbook_messages
  for insert
  to anon
  with check (
    char_length(btrim(name)) between 1 and 60
    and char_length(btrim(message)) between 1 and 500
  );

-- Private RSVP submissions. Visitors can submit; only the couple can view responses in the dashboard.
create table if not exists public.wedding_rsvps (
  id bigint generated by default as identity primary key,
  guest_name text not null check (char_length(btrim(guest_name)) between 1 and 100),
  attendance text not null check (attendance in ('joyfully accepts', 'regretfully declines')),
  guest_count smallint not null default 1 check (guest_count between 1 and 10),
  note text not null default '' check (char_length(btrim(note)) <= 500),
  created_at timestamptz not null default now()
);

create index if not exists wedding_rsvps_created_at_idx
  on public.wedding_rsvps (created_at desc);

alter table public.wedding_rsvps enable row level security;

revoke all on table public.wedding_rsvps from anon, authenticated;
grant insert (guest_name, attendance, guest_count, note) on public.wedding_rsvps to anon;
revoke all on sequence public.wedding_rsvps_id_seq from anon, authenticated;
grant usage, select on sequence public.wedding_rsvps_id_seq to anon;

drop policy if exists "Visitors can submit wedding RSVPs" on public.wedding_rsvps;
create policy "Visitors can submit wedding RSVPs"
  on public.wedding_rsvps
  for insert
  to anon
  with check (
    char_length(btrim(guest_name)) between 1 and 100
    and attendance in ('joyfully accepts', 'regretfully declines')
    and guest_count between 1 and 10
    and char_length(btrim(note)) <= 500
  );
